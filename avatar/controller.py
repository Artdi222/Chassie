"""Minimal avatar backend interface, implemented by the desktop and web renderers."""
from typing import Protocol


class AvatarController(Protocol):
    async def start(self) -> None: ...
    async def trigger_emotion(self, emotion: str) -> bool: ...
    async def preview_emotion(self, emotion: str) -> bool: ...
    async def set_parameter(self, param: str, value: float) -> bool: ...
    async def set_mouth_open(self, value: float) -> bool: ...
    async def reset_expressions(self) -> bool: ...
    async def reset(self) -> bool: ...
    async def disconnect(self) -> None: ...
    def get_capabilities(self) -> dict: ...
